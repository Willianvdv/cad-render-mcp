fn glyph(c: char) -> Option<&'static [&'static str; 7]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, b)| b)
}

/// RGBA8 image being annotated.
pub struct Canvas<'a> {
    pub px: &'a mut [u8],
    pub w: u32,
    pub h: u32,
}

impl Canvas<'_> {
    pub fn rect(&mut self, x: i32, y: i32, w: i32, h: i32, rgba: [u8; 4]) {
        let a = rgba[3] as u32;
        for yy in y.max(0)..(y + h).min(self.h as i32) {
            for xx in x.max(0)..(x + w).min(self.w as i32) {
                let i = ((yy as u32 * self.w + xx as u32) * 4) as usize;
                for (d, s) in self.px[i..i + 3].iter_mut().zip(&rgba[..3]) {
                    *d = ((*s as u32 * a + *d as u32 * (255 - a)) / 255) as u8;
                }
                self.px[i + 3] = self.px[i + 3].max(rgba[3]);
            }
        }
    }

    pub fn text_size(s: &str, scale: i32) -> (i32, i32) {
        (s.chars().count() as i32 * 6 * scale - scale, 7 * scale)
    }

    pub fn text(&mut self, x: i32, y: i32, s: &str, scale: i32, rgba: [u8; 4]) {
        let mut cx = x;
        for c in s.chars() {
            if let Some(g) = glyph(c) {
                for (row, bits) in g.iter().enumerate() {
                    for (col, b) in bits.bytes().enumerate() {
                        if b == b'#' {
                            self.rect(
                                cx + col as i32 * scale,
                                y + row as i32 * scale,
                                scale,
                                scale,
                                rgba,
                            );
                        }
                    }
                }
            }
            cx += 6 * scale;
        }
    }

    /// Text on a translucent plate, for legibility over geometry.
    pub fn label(&mut self, x: i32, y: i32, s: &str, scale: i32, fg: [u8; 4], bg: [u8; 4]) {
        let (w, h) = Self::text_size(s, scale);
        self.rect(
            x - 2 * scale,
            y - 2 * scale,
            w + 4 * scale,
            h + 4 * scale,
            bg,
        );
        self.text(x, y, s, scale, fg);
    }
}
